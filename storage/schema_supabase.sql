-- Схема Supabase для «Учебного навигатора» (блок С2).
-- Выполнить целиком в Supabase Dashboard → SQL Editor до запуска мигратора.
-- Повторный запуск безопасен: таблицы, индексы и функция создаются идемпотентно.

create table if not exists public.teachers (
    id bigint generated by default as identity primary key,
    name text,
    subject text,
    school text,
    telegram_user_id bigint unique,
    created_at timestamptz default current_timestamp
);

create table if not exists public.style_profiles (
    id bigint generated by default as identity primary key,
    teacher_id bigint references public.teachers(id),
    goal_phrasing text,
    stage_structure text,
    assessment_methods text,
    resources_used text,
    raw_samples_count integer,
    updated_at timestamptz
);

create table if not exists public.templates (
    id bigint generated by default as identity primary key,
    name text not null,
    description text,
    source text,
    is_official integer not null default 0 check (is_official in (0, 1)),
    is_builtin integer not null default 0 check (is_builtin in (0, 1)),
    category text not null default 'personal' check (category in ('official', 'sample', 'personal')),
    uploaded_by bigint references public.teachers(id),
    structure_json text not null,
    created_at timestamptz default current_timestamp
);

create table if not exists public.template_selections (
    telegram_user_id bigint primary key,
    template_id bigint not null references public.templates(id),
    selected_at timestamptz not null
);

create table if not exists public.curriculum_objectives (
    code text primary key,
    grade integer,
    section text,
    subsection text,
    description text,
    thinking_level text
);

create table if not exists public.ktp_entries (
    id bigint generated by default as identity primary key,
    teacher_id bigint references public.teachers(id),
    lesson_number integer,
    section text,
    topic text,
    objective_code text references public.curriculum_objectives(code),
    hours integer,
    planned_date text,
    quarter integer
);

create table if not exists public.generated_ksp (
    id text primary key,
    teacher_id bigint references public.teachers(id),
    ktp_entry_id bigint references public.ktp_entries(id),
    template_id bigint references public.templates(id),
    content_json text,
    docx_path text,
    created_at timestamptz default current_timestamp
);

create table if not exists public.tasks (
    id text primary key,
    -- 'sverka_tetradi' добавлен блоком У4 (PLAN.md). ⚠️ CREATE TABLE IF NOT
    -- EXISTS не меняет CHECK уже существующей таблицы — на прод, где
    -- tasks уже есть, это применяется отдельным ALTER TABLE через SQL
    -- Editor (готовый SQL — в отчёте по блоку У4), не автоматическим
    -- перезапуском этого файла.
    type text check (type in ('parse_ksp', 'generate_ksp', 'generate_ktp', 'transcribe', 'generate_konspekt', 'sverka_tetradi')),
    status text check (status in ('pending', 'processing', 'done', 'failed')) default 'pending',
    payload text,
    result text,
    error text,
    telegram_chat_id bigint,
    retries integer default 0,
    created_at timestamptz default current_timestamp,
    updated_at timestamptz
);

create table if not exists public.usage_daily (
    telegram_user_id bigint not null,
    day text not null,
    operation text not null,
    count integer not null default 0,
    tokens integer not null default 0,
    primary key (telegram_user_id, day, operation)
);

create table if not exists public.admin_access (
    telegram_user_id bigint primary key,
    expires_at text not null
);

create table if not exists public.transcripts (
    id text primary key,
    teacher_id bigint references public.teachers(id),
    ktp_entry_id bigint references public.ktp_entries(id),
    source text,
    mode text not null default 'student' check (mode in ('student', 'teacher')),
    text text not null,
    duration_seconds integer,
    language text,
    created_at timestamptz default current_timestamp
);

create table if not exists public.konspekty (
    id text primary key,
    teacher_id bigint references public.teachers(id),
    transcript_id text references public.transcripts(id),
    mode text not null default 'student' check (mode in ('student', 'teacher')),
    ktp_entry_id bigint references public.ktp_entries(id),
    tema text,
    content_json text not null,
    docx_path text,
    created_at timestamptz default current_timestamp
);

create table if not exists public.incidents (
    id bigint generated by default as identity primary key,
    started_at timestamptz not null,
    ended_at timestamptz,
    reason text not null,
    notified integer not null default 0
);

create table if not exists public.worker_heartbeat (
    id integer primary key check (id = 1),
    updated_at timestamptz not null default current_timestamp
);

-- consents — согласие на использование системы (блок Ю3, storage/schema.sql
-- несёт полное обоснование, почему отдельная таблица, а не колонка в
