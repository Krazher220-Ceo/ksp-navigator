"""
tests/test_bez_ii_posle_rasshifrovki.py — решение автора от 02.09.2026.

После расшифровки нейросеть в веб-пути не участвует: кабинет показывает
сам транскрипт с настоящими отметками времени, а обобщение случается
ровно один раз — при сборке КСП, отдельным промптом по всему уроку.

Раньше между ними стоял шаг «пересказать расшифровку в конспект». Он
терял формулировки педагога, а проверить пересказ можно было только
сверив с исходником, которого педагог не видел.

Путь бота при этом не меняется: у него флага нет, и его ученический
режим работает как работал.
"""

from pathlib import Path

import pytest

from core.ksp_generator import TASK_KONSPEKT_HEADER, TASK_TRANSCRIPT_HEADER, build_prompt
from core.transcript_blocks import ПАУЗА_СЕКУНД, как_время, собрать_блоки

PROJECT_ROOT = Path(__file__).resolve().parent.parent


# --- кабинет не зовёт нейросеть между расшифровкой и КСП ---

def test_кабинет_просит_не_собирать_конспект_нейросетью():
    api = (PROJECT_ROOT / "web" / "api_v1.py").read_text(encoding="utf-8")
    кусок = api[api.index('"transcribe"'):]
    кусок = кусок[: кусок.index("return")]
    assert '"konspekt_llm": False' in кусок, (
        "кабинет снова просит собрать конспект нейросетью"
    )


def test_у_бота_флага_нет_и_его_путь_не_изменился():
    """
    Умолчание True: задача без флага ведёт себя как раньше. Иначе одна
    правка в вебе молча меняет поведение бота.
    """
    handlers = (PROJECT_ROOT / "bot" / "handlers.py").read_text(encoding="utf-8")
    assert 'payload.get("konspekt_llm", True)' in handlers, (
        "умолчание изменилось — путь бота больше не прежний"
    )


# --- отдельный промпт для полной расшифровки ---

def test_полная_расшифровка_идёт_со_своей_шапкой():
    """
    Модель должна понимать, что перед ней сырая речь на сорок пять
    минут, а не выжимка. Иначе она примет расшифровку за конспект и
    начнёт раскладывать по этапам отступления и оговорки.
    """
    промпт = build_prompt(
        topic="Тема", razdel="Раздел", objective_code=None, klass="7",
        duration_minutes=45, konspekt_text="…и вот смотрите, ребята…",
        konspekt_is_transcript=True,
    )
    assert TASK_TRANSCRIPT_HEADER in промпт
    assert TASK_KONSPEKT_HEADER not in промпт


def test_собранный_конспект_идёт_с_прежней_шапкой():
    """Путь бота с настоящим конспектом не должен был измениться."""
    промпт = build_prompt(
        topic="Тема", razdel="Раздел", objective_code=None, klass="7",
        duration_minutes=45, konspekt_text="Главное с урока: …",
    )
    assert TASK_KONSPEKT_HEADER in промпт
    assert TASK_TRANSCRIPT_HEADER not in промпт


def test_шапка_расшифровки_требует_реальных_реплик():
    """
    Это и есть та «отдельная строка промпта», ради которой всё
    затевалось: взять основные реплики из урока и не сочинять речь.
    """
    assert "основные реплики" in TASK_TRANSCRIPT_HEADER
    assert "Не сочиняй речь" in TASK_TRANSCRIPT_HEADER
    assert "расшифровка" in TASK_TRANSCRIPT_HEADER.lower()


def test_кабинет_помечает_материал_как_расшифровку():
    api = (PROJECT_ROOT / "web" / "api_v1.py").read_text(encoding="utf-8")
    assert '"konspekt_is_transcript": bool(konspekt_text)' in api


# --- реплики собираются арифметикой, а не нейросетью ---

def test_в_разборе_реплик_нет_ни_одного_вызова_нейросети():
    """Модуль обязан остаться арифметикой: это его единственный смысл."""
    модуль = (PROJECT_ROOT / "core" / "transcript_blocks.py").read_text(encoding="utf-8")
    for запрещённое in ("LLMClient", "llm", "httpx", "openai", "prompt"):
        assert запрещённое not in модуль, f"в разборе реплик появился {запрещённое}"


def test_новая_реплика_начинается_после_паузы():
    слова = [
        {"text": "итак", "start": 0.0, "end": 0.4},
        {"text": "записали", "start": 0.5, "end": 1.0},
        # пауза больше порога — здесь проходит граница
        {"text": "теперь", "start": 1.0 + ПАУЗА_СЕКУНД + 0.2, "end": 3.0},
    ]
    блоки = собрать_блоки(слова)
    assert len(блоки) == 2
    assert блоки[0]["text"] == "итак записали"
    assert блоки[1]["text"] == "теперь"


@pytest.mark.parametrize("слово", [
    {"text": "без", "start": None, "end": 1.0},
    {"text": "времени", "start": 1.0, "end": None},
    {"text": "", "start": 1.0, "end": 2.0},
])
def test_время_не_выдумывается(слово):
    """
    Слово без отметки в блок не попадает. Показать педагогу
    правдоподобное «примерно тут» — то же самое, что соврать: он по
    этим отметкам потом отчитается.
    """
    блоки = собрать_блоки([слово])
    assert блоки == []


def test_пустой_список_слов_это_не_ошибка():
    """Старые записи отметок не имеют — экран показывает текст целиком."""
    assert собрать_блоки([]) == []


@pytest.mark.parametrize("секунды,ожидается", [(0, "00:00"), (61, "01:01"), (3661, "1:01:01")])
def test_время_показывается_как_на_плеере(секунды, ожидается):
    assert как_время(секунды) == ожидается


