"""
tests/core/test_login_codes.py — вход в кабинет подтверждением в боте.

Что здесь сторожится и почему именно это. Функция появилась затем, чтобы
у входа через Telegram перестал спрашиваться НОМЕР ТЕЛЕФОНА: Login Widget
уводит на oauth.telegram.org, а тот на телефоне почти всегда просит
номер. Значит, главный тест файла — не «код выдаётся», а то, что талон
одноразовый и недолгий: это единственное, что стоит между ссылкой в чужом
чате и чужим кабинетом.

Чего эти тесты осознанно не делают: не проверяют подпись данных входа —
она общая с Login Widget и проверена в tests/web/test_telegram_login.py.
Второй проверки подписи в проекте нет и заводить её нельзя.
"""

from datetime import datetime, timedelta, timezone

import pytest

from core.db import execute, query
from core.login_codes import (
    DEEP_LINK_PREFIX,
    LOGIN_CODE_TTL,
    LoginCodeError,
    выдать_код,
    забрать_подтверждённый,
    контрольные_знаки,
    код_ждёт_подтверждения,
    подтвердить,
    построить_ссылку,
    убрать_протухшие,
)


def _просрочить(код: str) -> None:
    """Двигает срок годности в прошлое — так же, как это сделало бы время."""
    прошлое = (datetime.now(timezone.utc) - timedelta(minutes=1)).isoformat()
    execute("UPDATE login_codes SET expires_at = ? WHERE code = ?", (прошлое, код))


def test_код_выдаётся_и_живёт_пять_минут():
    выдан = выдать_код()
    assert выдан["живёт_секунд"] == int(LOGIN_CODE_TTL.total_seconds()) == 300
    строки = query("SELECT status FROM login_codes WHERE code = ?", (выдан["код"],))
    assert строки[0]["status"] == "pending"


def test_два_вызова_дают_разные_коды():
    """Предсказуемый код — это вход, который можно угадать."""
    assert выдать_код()["код"] != выдать_код()["код"]


def test_код_годится_для_ссылки_telegram():
    """Telegram принимает в start только A-Z a-z 0-9 _ и дефис.

    Знак вне этого набора Telegram молча обрежет, и код доедет до бота
    покалеченным — вход «просто не работает», без единой ошибки в логе.
    """
    код = выдать_код()["код"]
    assert all(з.isalnum() or з in "_-" for з in код), код
    ссылка = построить_ссылку(код, "ksp_navigator_bot")
    assert ссылка == f"https://t.me/ksp_navigator_bot?start={DEEP_LINK_PREFIX}{код}"


def test_контрольные_знаки_одинаковы_у_сайта_и_бота():
    """Сверять человеку нечего, если сайт и бот показывают разное."""
    выдан = выдать_код()
    assert выдан["контрольные_знаки"] == контрольные_знаки(выдан["код"])
    assert len(выдан["контрольные_знаки"]) == 4


def test_неподтверждённый_код_ещё_не_вход():
    """Пока человек не нажал кнопку в боте, сайт не получает ничего.

    Это и есть защита от «уговорили открыть ссылку»: открытие ссылки
    само по себе не пускает никуда.
    """
    код = выдать_код()["код"]
    assert забрать_подтверждённый(код) is None


def test_подтверждённый_код_отдаётся_ровно_один_раз():
    """Код, отданный дважды, — это вход, которым можно войти дважды."""
    код = выдать_код()["код"]
    подтвердить(код, 4242, first_name="Алихан", username="alikhan")

    первый = забрать_подтверждённый(код)
    assert первый["telegram_user_id"] == 4242
    assert первый["first_name"] == "Алихан"

    with pytest.raises(LoginCodeError):
        забрать_подтверждённый(код)


def test_просроченный_код_не_подтверждается():
    код = выдать_код()["код"]
    _просрочить(код)
    with pytest.raises(LoginCodeError):
        подтвердить(код, 4242)
    with pytest.raises(LoginCodeError):
        код_ждёт_подтверждения(код)


def test_просроченный_код_не_превращается_во_вход():
    """Подтверждён вовремя, забран поздно — всё равно мимо."""
    код = выдать_код()["код"]
    подтвердить(код, 4242)
    _просрочить(код)
    with pytest.raises(LoginCodeError):
        забрать_подтверждённый(код)


def test_несуществующий_код_это_ошибка_а_не_ожидание():
    with pytest.raises(LoginCodeError):
        забрать_подтверждённый("такого-кода-нет")


def test_повторное_подтверждение_не_проходит():
    """Иначе один талон можно перевесить на другого человека."""
    код = выдать_код()["код"]
    подтвердить(код, 4242)
    with pytest.raises(LoginCodeError):
        код_ждёт_подтверждения(код)


def test_чистка_убирает_протухшие_и_использованные():
    живой = выдать_код()["код"]
    протухший = выдать_код()["код"]
    _просрочить(протухший)
    использованный = выдать_код()["код"]
    подтвердить(использованный, 7)
    забрать_подтверждённый(использованный)

    убрать_протухшие()

    осталось = {с["code"] for с in query("SELECT code FROM login_codes")}
    assert живой in осталось
    assert протухший not in осталось
    assert использованный not in осталось


def test_ни_одно_поле_таблицы_не_про_телефон():
    """Смысл всей затеи: номер телефона не хранится и не спрашивается.

    Если в этой таблице однажды появится колонка под номер — значит
    вернулись к тому, от чего уходили.
    """
    выдать_код()
    колонки = set(query("SELECT * FROM login_codes")[0].keys())
    assert not {к for к in колонки if "phone" in к or "телефон" in к}
    assert колонки == {
        "code", "status", "telegram_user_id", "first_name", "username",
        "expires_at", "created_at",
    }
