"""
tests/test_frontend_adaptive.py — сайт и кабинет на телефоне и планшете.

Сторожит то, из-за чего страница ломается на узком экране незаметно для
того, кто смотрит её на ноутбуке: жёсткие поля в 56px, заголовок в 56px,
сетка в три колонки по 100px и ряд кнопок, который не переносится.

Проверяются исходники, браузера здесь нет. Живой прогон делался
отдельно: на 375, 768 и 1024 у лендинга, документации, входа,
регистрации и семи экранов кабинета ноль элементов, вылезающих за
правый край.
"""

import re
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parent.parent
FRONTEND = PROJECT_ROOT / "frontend"
ADAPTIVE_CSS = FRONTEND / "app" / "adaptive.css"

# Дэшборд собран на двенадцати колонках с span у детей: auto-fit его бы
# сломал, поэтому он складывается медиазапросом и в проверке ниже
# исключён по классу, а не по имени файла.
СЕТКА_ДЭШБОРДА = "repeat(12,minmax(0,1fr))"


def _исходники(маска: str = "*.tsx") -> dict[str, str]:
    файлы = {}
    for корень in ("components", "app"):
        for путь in (FRONTEND / корень).rglob(маска):
            if "node_modules" in путь.parts or ".next" in путь.parts:
                continue
            файлы[str(путь.relative_to(FRONTEND))] = путь.read_text(encoding="utf-8")
    return файлы


# --- поля и типографика ---

def test_поля_секций_едут_вместе_с_экраном():
    """
    56px по бокам на телефоне в 375px — это треть экрана под пустоту.

    Значение не выкинуто, а стало верхней границей clamp(): на ноутбуке
    поле ровно такое, как в макете, и сжимается только когда места
    действительно меньше.
    """
    жёсткие = []
    for имя, текст in _исходники().items():
        for место in re.finditer(r"padding: '([^']*)'", текст):
            значение = место.group(1)
            # Внутри clamp() 56px — это верхняя граница, а не жёсткое
            # поле: ровно то, к чему всё и приводилось.
            if "clamp(" in значение or "var(--pad-x)" in значение:
                continue
            if re.search(r"\b(56|44)px", значение):
                жёсткие.append(f"{имя}: {значение}")
    assert жёсткие == [], "поля секции снова жёсткие: " + "; ".join(жёсткие)

    css = ADAPTIVE_CSS.read_text(encoding="utf-8")
    assert "--pad-x: clamp(" in css, "переменная полей пропала"
    # Верхняя граница обязана совпасть с макетом, иначе на ноутбуке
    # страница поедет против утверждённого артборда.
    assert "56px)" in css


@pytest.mark.parametrize("файл,было", [
    ("components/landing/Hero.tsx", 56),
    ("components/landing/CallToAction.tsx", 40),
    ("app/(site)/docs/page.tsx", 40),
])
def test_крупные_заголовки_сжимаются(файл, было):
    """Заголовок в 56px на телефоне переносится по слогам и рвёт вёрстку."""
    текст = (FRONTEND / файл).read_text(encoding="utf-8")
    assert f"fontSize: {было}," not in текст, "размер снова жёсткий"
    assert f"{было}px)" in текст, "макетный размер потерян как верхняя граница"


# --- сетки ---

def test_равных_колонок_с_жёстким_числом_не_осталось():
    """
    '1fr 1fr' и 'repeat(3, 1fr)' на телефоне дают колонки по 100px, в
    которые не влезает ни одно слово. Единственное исключение —
    переключатель из двух кнопок в одной таблетке: он один орган
    управления и складываться не должен.
    """
    виновные = []
    for имя, текст in _исходники().items():
        for место in re.finditer(r"gridTemplateColumns: '(1fr 1fr[^']*|repeat\(\d[^']*)'", текст):
            значение = место.group(1)
            вокруг = текст[max(0, место.start() - 320): место.start()]
            переключатель = 'role="radiogroup"' in вокруг or 'role="tablist"' in вокруг
            if значение == "1fr 1fr" and (переключатель or "RoleSwitch" in имя):
                continue
            if значение == СЕТКА_ДЭШБОРДА:
                assert "dash-grid" in текст, "сетка дэшборда осталась без класса"
                continue
            виновные.append(f"{имя}: {значение}")
    assert виновные == [], "жёсткие сетки: " + "; ".join(виновные)


def test_соотношения_колонок_живут_в_переменной():
    """
    Inline grid-template-columns перекрыть медиазапросом нельзя, а
    переменную — можно. Поэтому соотношение из макета уезжает в --split,
    а раскладку на узком решает CSS.
    """
    осталось = []
    for имя, текст in _исходники().items():
        for место in re.finditer(r"gridTemplateColumns: '(minmax\(0|\d+px minmax)", текст):
            осталось.append(f"{имя}: {текст[место.start():место.start() + 60]}")
    assert осталось == [], "соотношение снова вшито в разметку: " + "; ".join(осталось)

    css = ADAPTIVE_CSS.read_text(encoding="utf-8")
    assert ".split { display: grid; grid-template-columns: var(--split); }" in css
    сложение = re.search(r"@media \(max-width: 720px\) \{(.+?)\n\}", css, re.S)
    assert сложение and "grid-template-columns: minmax(0, 1fr)" in сложение.group(1), (
        "на узком колонки больше не складываются"
    )


