@pytest.mark.parametrize("класс", ["nav-sections", "nav-cta", "docs-search", "top-search", "foot-links", "school-row"])
def test_тесные_ряды_разобраны_поимённо(класс):
    """
    Каждый ряд, который на узком экране уезжал за край, назван классом и
    разобран в adaptive.css. Класс без правила — забытая правка.
    """
    css = ADAPTIVE_CSS.read_text(encoding="utf-8")
    assert f".{класс}" in css, f"класс {класс} остался без правила"
    разметка = "\n".join(_исходники().values())
    assert класс in разметка, f"класс {класс} нигде не проставлен"


# --- пороги ---

def test_пороги_объяснены_а_не_подобраны():
    """
    Каждый медиазапрос сопровождается объяснением, от чего взят порог.
    Иначе через месяц никто не помнит, почему 860, и правит наугад.
    """
    css = ADAPTIVE_CSS.read_text(encoding="utf-8")
    пороги = set(re.findall(r"max-width: (\d+)px", css))
    assert пороги, "медиазапросы пропали"
    # Три несущих порога описаны в шапке файла поимённо.
    шапка = css[: css.index("*/")]
    for порог in ("1100", "860", "720"):
        assert порог in шапка, f"порог {порог}px не объяснён в шапке"


def test_кабинет_на_планшете_не_отдаёт_меню_четверть_экрана():
    """Между телефоном и ноутбуком полоса меню сужается, а не исчезает."""
    css = ADAPTIVE_CSS.read_text(encoding="utf-8")
    планшет = re.search(r"@media \(min-width: 861px\) and \(max-width: 1180px\) \{(.+?)\n\}", css, re.S)
    assert планшет, "правило планшета пропало"
    assert "grid-template-columns: 200px" in планшет.group(1)


# --- кнопки, которые ничего не делают ---

def test_во_всём_проекте_нет_кнопок_в_никуда():
    """
    Кнопка обязана либо вести по ссылке, либо что-то делать, либо быть
    честно выключенной. «Выглядит рабочей, но мёртвая» — худшее из трёх:
    человек нажимает и решает, что сломался продукт.

    Витрина компонентов /kit исключена: там кнопки показываются как
    образцы вёрстки, нажимать их не на что.
    """
    подозрительные = []
    for имя, текст in _исходники().items():
        if имя.startswith("app/kit"):
            continue
        for место in re.finditer(r"<Button\b", текст):
            начало = место.start()
            кусок = текст[начало: начало + 900]
            конец = кусок.find("</Button>")
            кнопка = кусок[: конец if конец != -1 else 900]
            до = текст[max(0, начало - 300): начало]
            живая = (
                "href=" in до
                or "onClick" in кнопка
                or "type=\"submit\"" in кнопка
                or "disabled" in кнопка
                or "aria-disabled" in кнопка
            )
            if not живая:
                подпись = re.sub(r"\s+", " ", кнопка)[:64]
                подозрительные.append(f"{имя}: {подпись}")
    assert подозрительные == [], "кнопки, которые ничего не делают: " + "; ".join(подозрительные)


def test_в_меню_кабинета_нет_пунктов_без_адреса():
    """
    Пункт без href рисуется обычным блоком и молчит при нажатии. Такие
    оставались, пока не было соответствующих страниц; теперь страницы
    есть, и молчащих пунктов быть не должно — кроме честно закрытых
    замком.
    """
    меню = (FRONTEND / "components" / "Sidebar.tsx").read_text(encoding="utf-8")
    блок = меню[меню.index("export const NAV: Group[]"):]
    блок = блок[: блок.index("type Props")]
    немые = []
    for пункт in re.finditer(r"\{ key: '([^']+)'[^}]*\}", блок):
        текст = пункт.group(0)
        if "href:" not in текст and "locked: true" not in текст:
            немые.append(пункт.group(1))
    assert немые == [], f"пункты меню без адреса и без замка: {немые}"


def test_все_разделы_документации_написаны():
    """
    Семь из восьми разделов стояли в списке неактивным текстом: страниц
    не существовало. Читателю это выглядит как недоделанный продукт.
    """
    исходник = (FRONTEND / "content" / "docs-razdely.ts").read_text(encoding="utf-8")
    ключи = re.findall(r"ключ: '([^']+)'", исходник)

    # В списке слева восемь разделов. Семь написаны по общему шаблону,
    # восьмой — «Аналитика продукта» — живёт отдельной страницей /docs:
    # она свёрстана по своему артборду, и переливать её в общий шаблон
    # значило бы потерять утверждённую вёрстку ради единообразия.
    список = (FRONTEND / "content" / "docs.ts").read_text(encoding="utf-8")
    все = re.findall(r"ключ: '([^']+)'", список[список.index("РАЗДЕЛЫ_ДОКУМЕНТАЦИИ"):])
    assert len(все) == 8, f"список разделов изменился: {все}"
    без_страницы = [к for к in все if к not in ключи and к != "analitika"]
    assert без_страницы == [], f"разделы без написанного текста: {без_страницы}"

    # У каждого раздела есть подзаголовок и хотя бы две главы с текстом:
    # раздел из одного заголовка хуже отсутствующего, он обещает ответ.
    for ключ in ключи:
        кусок = исходник[исходник.index(f"ключ: '{ключ}'"):]
        конец = кусок.find("ключ: '", 10)
        кусок = кусок[: конец if конец != -1 else len(кусок)]
        assert "подзаголовок:" in кусок, f"раздел {ключ} без подзаголовка"
        assert кусок.count("якорь:") >= 2, f"раздел {ключ} короче двух глав"

    # И все они доступны ссылкой из списка слева.
    список = (FRONTEND / "components" / "landing" / "РазделыСлева.tsx").read_text(encoding="utf-8")
    assert "<Link" in список, "разделы снова нарисованы неактивным текстом"
