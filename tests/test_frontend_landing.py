# --- тарифы ---

def _числа(текст: str) -> set[str]:
    """Денежные суммы вида «3 490 ₸», приведённые к виду без пробелов."""
    return {м.replace(" ", " ").replace(" ", "") for м in re.findall(r"\d[\d  ]*\s*₸", текст)}


@pytest.mark.parametrize("сумма", [
    "3 490 ₸", "29 000 ₸", "9 900 ₸", "79 000 ₸", "990 ₸", "2 990 ₸", "2 490 ₸",
])
def test_цены_совпадают_с_tariffs_md(сумма):
    """Сетка на сайте — та же, что в design/TARIFFS.md, редакция 01.09."""
    из_файла = _числа(TARIFFS_MD.read_text(encoding="utf-8"))
    из_кода = _числа(TARIFFS_TS.read_text(encoding="utf-8"))
    ключ = сумма.replace(" ", "")
    assert ключ in из_файла, f"{сумма} исчезло из design/TARIFFS.md — сверить сетку"
    assert ключ in из_кода, f"{сумма} не доехало до сайта"


def test_старых_цен_на_сайте_не_осталось():
    """Числа питча 28.08 (2 490 / 4 900 / 690 / 1 190) заменены целиком."""
    из_кода = _числа(TARIFFS_TS.read_text(encoding="utf-8"))
    # 2 490 ₸ — цена места в школе, она в новой сетке есть и остаётся.
    assert "4900₸" not in из_кода
    assert "690₸" not in из_кода
    assert "1190₸" not in из_кода


def test_слова_безлимитно_там_где_есть_потолок_нет():
    """На «Учителе» 5 черновиков КСП и 2 конспекта в сутки — не безлимит."""
    текст = _исходники()["content/tariffs.ts"]
    учитель = текст[текст.index("ключ: 'teacher'") : текст.index("ключ: 'teacher_pro'")]
    assert "безлимит" not in учитель.lower()
    assert "5 черновиков КСП в день" in учитель
    assert "2 конспекта из записи в день" in учитель


def test_скидок_и_таймеров_на_сайте_нет():
    """Ни «−70%, только сегодня», ни обратного отсчёта (TARIFFS.md §7)."""
    запрещено = ["только сегодня", "осталось", "успей", "скидк", "−70", "-70%"]
    найдено = [
        f"{имя}: {слово}"
        for имя, текст in _исходники().items()
        if имя.startswith(("app/(site)", "components/landing", "content/tariffs"))
        for слово in запрещено if слово in текст.lower()
    ]
    assert найдено == [], f"на сайте появились приёмы распродажи: {найдено}"


