    страницы = "\n".join(
        текст for имя, текст in _исходники().items()
        if имя.startswith(("app/(site)", "components/landing"))
    )
    assert "не уходит наружу" not in страницы
    assert "не покидает" not in страницы
    assert "сразу после этого\n            удаляется" in страницы or "удаляется" in страницы


