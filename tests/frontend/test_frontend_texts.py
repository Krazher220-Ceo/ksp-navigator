def test_на_сайте_не_осталось_команд_телеграма():
    """
    «Наберите /start» и «командой /sverka» на сайте — инструкция к
    другому продукту. Автор наткнулся на это на экране регистрации
    02.09.2026.
    """
    содержимое = ВЫГРУЗКА.read_text(encoding="utf-8")
    команды = re.findall(r"/(?:start|join|sverka|delete_my_data|teacher|konspekt)\b", содержимое)
    assert команды == [], f"в текстах кабинета остались команды бота: {sorted(set(команды))}"


def test_веб_редакция_меняет_только_способ_связи():
    """
    Юридически значимые абзацы обязаны совпадать с ботом дословно.

    Развести можно «наберите /start» и «откройте страницу заново».
    Развести трансграничную передачу или согласие законного
    представителя — нельзя: это разные обещания разным людям об одном и
    том же продукте.
    """
    неприкосновенные = [
        "⚠️ Расшифровка выполняется внешним провайдером за пределами "
        "Республики Казахстан — это трансграничная передача данных.",
        "Аудиозапись урока удаляется сразу после расшифровки — на диске не "
        "остаётся.",
    ]
    for абзац in неприкосновенные:
        assert абзац in texts.CONSENT_TEXT
        assert абзац in texts_web.CONSENT_TEXT, "юридический абзац переписан в веб-редакции"

    ученик = (
        "⚠️ Если вам ещё нет 18 лет, для использования системы требуется "
        "согласие вашего законного представителя (родителя или опекуна) — "
        "убедитесь, что оно есть, прежде чем продолжать."
    )
    assert ученик in texts.STUDENT_CONSENT_TEXT
    assert ученик in texts_web.STUDENT_CONSENT_TEXT


def test_веб_редакция_заведена_только_там_где_нужна():
    """
    Лишняя веб-редакция — вторая копия текста, которая разойдётся с
    ботом при первой же правке. Заводить её без причины нельзя.
    """
    свои = [и for и in dir(texts_web) if и.isupper()]
    assert свои, "веб-редакции пропали"
    for имя in свои:
        у_бота = getattr(texts, имя, None)
        assert у_бота is not None, f"{имя} нет у бота — имя разошлось"
        assert getattr(texts_web, имя) != у_бота, (
            f"веб-редакция {имя} слово в слово повторяет бота — она лишняя"
        )
