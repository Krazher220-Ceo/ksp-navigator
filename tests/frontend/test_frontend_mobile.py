def _тело_функции(исходник: str, имя: str) -> str:
    """Кусок api.ts от объявления функции до следующего объявления."""
    начало = исходник.index(f"function {имя}(")
    хвост = исходник[начало:]
    следующая = хвост.find("\nexport ", 1)
    return хвост if следующая == -1 else хвост[:следующая]


def test_все_загрузки_файлов_ставят_заголовки_одним_сборщиком():
    """
    Три загрузки — запись урока, КТП и фото тетради — собирали заголовки
    каждая по-своему, и копии разошлись: у записи блок входа через
    Telegram оказался продублирован, а у фото тетради его не было
    вовсе. Ученик, вошедший на сайте виджетом Telegram, получал 401 на
    сверке тетради — своей главной и единственной функции.

    Проверяется не число копий (их и не должно быть), а то, что каждая
    загрузка идёт через общий сборщик: тогда забыть дверь физически
    негде.
    """
    api = API_TS.read_text(encoding="utf-8")
    assert "async function заголовкиЗагрузки(" in api, "общий сборщик заголовков загрузки пропал"

    for имя in ("отправитьЗапись", "отправитьКтп", "отправитьФотоТетради"):
        тело = _тело_функции(api, имя)
        assert "заголовкиЗагрузки(" in тело, (
            f"{имя} собирает заголовки сама — рано или поздно одна из копий разойдётся"
        )
        assert "getSession()" not in тело, (
            f"{имя} снова читает сессию сама, минуя общий сборщик"
        )


def test_подпись_входа_в_браузере_не_проверяется():
    """
    Проверка подписи в браузере ничего не защищает: токен бота знает
    только сервер. Появившийся здесь hmac означал бы, что токен уехал
    в клиентский бандл.
    """
    хранилище = (FRONTEND / "lib" / "telegramLogin.ts").read_text(encoding="utf-8")
    for опасное in ("hmac", "BOT_TOKEN", "createHmac", "sha256"):
        assert опасное.lower() not in хранилище.lower(), (
            f"в браузерном коде появилось {опасное} — токен бота там оказаться не должен"
        )
