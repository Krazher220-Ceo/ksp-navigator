'use client';

import { useEffect, useState } from 'react';
import { НА_ЭТОЙ_СТРАНИЦЕ } from '@/content/docs';

/**
 * Оглавление документации с подсветкой раздела, который человек читает.
 *
 * Зачем модуль: раньше это был статический список ссылок — по нему
 * страница прыгала рывком, и после прыжка было непонятно, где ты
 * оказался. Теперь переход плавный (scroll-behavior в globals.css), а
 * текущий раздел выделен.
 *
 * Что осознанно не делает: не переписывает адрес в строке браузера сам.
 * Якорь ставит обычный переход по ссылке — на этом и держится работа
 * без JS: список остаётся ссылками, подсветка лишь добавляется.
 *
 * На что опирается: IntersectionObserver — тот же приём, что у
 * components/landing/Reveal.tsx. Слушателя scroll здесь нет намеренно:
 * он дёргается на каждый пиксель.
 */
export function Оглавление() {
  const [активный, setАктивный] = useState<string | null>(null);

  useEffect(() => {
    const заголовки = НА_ЭТОЙ_СТРАНИЦЕ
      .map((пункт) => document.getElementById(пункт.якорь))
      .filter((элемент): элемент is HTMLElement => элемент !== null);
    if (заголовки.length === 0) return;

    const наблюдатель = new IntersectionObserver(
      (записи) => {
        const видимые = записи.filter((запись) => запись.isIntersecting);
        if (видимые.length === 0) return;
        // Активным считается самый верхний из видимых заголовков: на
        // экран их попадает несколько, а читают всегда верхний.
        const верхний = видимые.reduce((а, б) =>
          а.boundingClientRect.top <= б.boundingClientRect.top ? а : б);
        setАктивный(верхний.target.id);
      },
      // Верхняя граница отодвинута на высоту липкой шапки, нижняя
      // поднята: раздел считается «читаемым», пока он в верхней трети.
      { rootMargin: '-84px 0px -68% 0px' },
    );
    заголовки.forEach((заголовок) => наблюдатель.observe(заголовок));
    return () => наблюдатель.disconnect();
  }, []);

  return (
    <div className="toc">
      {НА_ЭТОЙ_СТРАНИЦЕ.map((пункт) => (
        <a
          key={пункт.якорь}
          href={`#${пункт.якорь}`}
          className={активный === пункт.якорь ? 'toc-link on' : 'toc-link'}
          aria-current={активный === пункт.якорь ? 'true' : undefined}
          style={{ paddingLeft: пункт.вложенный ? 12 : 0 }}
        >
          {пункт.текст}
        </a>
      ))}
    </div>
  );
}
