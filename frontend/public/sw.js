/*
 * Service worker кабинета Mazmun (блок Ф12).
 *
 * Что кэшируется:
 *   — оболочка приложения и статика Next.js, чтобы кабинет открывался
 *     без сети;
 *   — готовые документы (/api/v1/download/...) — «офлайн-чтение уже
 *     открытых конспектов и планов» это ровно про них.
 *
 * Что НЕ кэшируется никогда:
 *   — расшифровки уроков и содержимое конспектов (/api/v1/konspekt/...),
 *   — результаты сверки тетради и всё остальное под /api/.
 * Причина простая: расшифровка урока и фотография чужой тетради — это
 * то, чему в кэше браузера не место. Документ педагог и так скачал себе
 * сам, а расшифровку он видит только на сервере.
 *
 * Версия кэша меняется руками при каждом изменении этого файла. Service
 * worker, оставшийся со старым бандлом, — классическая причина «у меня
 * всё сломалось»: при активации старые кэши удаляются целиком.
 */

// v2 — 02.09.2026: в кабинете появились экраны КТП и шаблонов,
// расшифровка стала показываться репликами. Старый кэш оболочки
// после этого не нужен и удаляется при активации.
const ВЕРСИЯ = 'mazmun-v2';
const КЭШ_ОБОЛОЧКИ = `${ВЕРСИЯ}-shell`;
const КЭШ_ДОКУМЕНТОВ = `${ВЕРСИЯ}-docs`;
const НАШИ_КЭШИ = [КЭШ_ОБОЛОЧКИ, КЭШ_ДОКУМЕНТОВ];

// Страница, которую показываем, если сети нет, а нужной страницы в кэше
// ещё не было. Отдельного офлайн-экрана не заводим: кабинет и так живёт
// на одном адресе, и его оболочка кэшируется первой же загрузкой.
const ЗАПАСНАЯ_СТРАНИЦА = '/app';

self.addEventListener('install', (событие) => {
  событие.waitUntil(
    caches.open(КЭШ_ОБОЛОЧКИ).then((кэш) => кэш.addAll([ЗАПАСНАЯ_СТРАНИЦА])).catch(() => undefined),
  );
  // Новая версия начинает работать сразу, не дожидаясь закрытия всех
  // вкладок: иначе исправление доезжает до человека через сутки.
  self.skipWaiting();
});

self.addEventListener('activate', (событие) => {
  событие.waitUntil(
    caches.keys().then((имена) => Promise.all(
      имена.filter((имя) => !НАШИ_КЭШИ.includes(имя)).map((имя) => caches.delete(имя)),
    )).then(() => self.clients.claim()),
  );
});

function этоДокумент(url) {
  return url.pathname.startsWith('/api/v1/download/');
}

function этоApi(url) {
  return url.pathname.startsWith('/api/');
}

function этоСтатика(url) {
  return url.pathname.startsWith('/_next/static/')
    || /\.(png|jpg|jpeg|svg|webmanifest|woff2?)$/.test(url.pathname);
}

self.addEventListener('fetch', (событие) => {
  const запрос = событие.request;
  if (запрос.method !== 'GET') return;

  const url = new URL(запрос.url);
  if (url.origin !== self.location.origin && !этоДокумент(url)) {
    // Чужие адреса не трогаем вовсе: API живёт на другом происхождении,
    // и лезть в его ответы кэшем — верный способ отдать вчерашние числа.
    return;
  }

  if (этоДокумент(url)) {
    // Документ собран один раз и больше не меняется — можно отдать из
    // кэша, а свежий положить рядом.
    событие.respondWith(
      caches.open(КЭШ_ДОКУМЕНТОВ).then(async (кэш) => {
        const изКэша = await кэш.match(запрос);
        if (изКэша) return изКэша;
        const ответ = await fetch(запрос);
        if (ответ.ok) кэш.put(запрос, ответ.clone());
        return ответ;
      }),
    );
    return;
  }

  if (этоApi(url)) {
    // Всё остальное под /api/ — только из сети. Расшифровкам, конспектам
    // и результатам сверки в кэше не место.
    return;
  }

  if (этоСтатика(url)) {
    событие.respondWith(
      caches.open(КЭШ_ОБОЛОЧКИ).then(async (кэш) => {
        const изКэша = await кэш.match(запрос);
        if (изКэша) return изКэша;
        const ответ = await fetch(запрос);
        if (ответ.ok) кэш.put(запрос, ответ.clone());
        return ответ;
      }),
    );
    return;
  }

  if (запрос.mode === 'navigate') {
    // Страницы: сначала сеть, кэш — запасной путь. Так человек всегда
    // видит свежую версию, если сеть есть.
    событие.respondWith(
      fetch(запрос)
        .then((ответ) => {
          const копия = ответ.clone();
          caches.open(КЭШ_ОБОЛОЧКИ).then((кэш) => кэш.put(запрос, копия)).catch(() => undefined);
          return ответ;
        })
        .catch(async () => (await caches.match(запрос)) || (await caches.match(ЗАПАСНАЯ_СТРАНИЦА))),
    );
  }
});
