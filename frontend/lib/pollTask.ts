'use client';

import { апи, type Задача } from './api';

/**
 * Опрос статуса задачи с замедляющимся шагом.
 *
 * Первые секунды спрашиваем часто — расшифровка урока укладывается в
 * десятки секунд, и ответ хочется увидеть сразу. Дальше пауза растёт до
 * пятнадцати секунд: висящая вкладка не должна долбить сервер раз в две
 * секунды час подряд.
 *
 * Опрос не подменяет гарантию уведомления из core/queue.py: она шлёт
 * сообщение в Telegram всем, у кого чат есть. Это второй канал — для
 * тех, кто вошёл по почте.
 */
const ШАГИ_СЕКУНД = [2, 2, 3, 3, 5, 5, 8, 8, 12, 15];

export function пауза(номерПопытки: number): number {
  return ШАГИ_СЕКУНД[Math.min(номерПопытки, ШАГИ_СЕКУНД.length - 1)] * 1000;
}

export type Остановка = () => void;

export function следитьЗаЗадачей(
  task_id: string,
  наИзменение: (задача: Задача) => void,
  наОшибку: (сообщение: string) => void,
): Остановка {
  let попытка = 0;
  let остановлено = false;
  let таймер: ReturnType<typeof setTimeout> | undefined;

  async function шаг() {
    if (остановлено) return;
    try {
      const задача = await апи.задача(task_id);
      наИзменение(задача);
      if (задача.status === 'done' || задача.status === 'failed') return;
    } catch (e) {
      наОшибку(e instanceof Error ? e.message : 'Не удалось узнать статус задачи.');
    }
    таймер = setTimeout(шаг, пауза(попытка++));
  }

  void шаг();
  return () => {
    остановлено = true;
    if (таймер) clearTimeout(таймер);
  };
}
