"""
core/login_codes.py — вход в кабинет подтверждением в боте, без номера телефона.

Зачем модуль: до него единственной дверью «войти через Telegram» был
Telegram Login Widget. Он открывает страницу oauth.telegram.org, и та
просит **номер телефона**, если человек не залогинен в Telegram Web в
этом самом браузере. На телефоне это происходит почти всегда: педагог
видит форму ввода номера вместо входа, вводит его, ждёт код — и часто не
доходит до конца. Номер при этом уходит Telegram, не нам, но человеку от
этого не легче: он ввёл номер и не вошёл.

Здесь вход устроен иначе и номер не спрашивается ни разу: сайт выдаёт
одноразовый код, человек открывает бота по ссылке с этим кодом, бот
видит его настоящий telegram-идентификатор (Telegram уже подтвердил, кто
это, самим фактом сообщения от него) и подтверждает вход кнопкой. Сайт
ждёт подтверждения и заходит.

Что осознанно не делает: не выдаёт сессию и не проверяет подпись. Код
здесь — только одноразовый талон «этот браузер и этот telegram-аккаунт
это один человек». Талон обменивается на обычные подписанные данные
входа в web/api_v1.py тем же форматом, что отдаёт виджет, — чтобы вся
проверка ниже (web/auth.verify_login_widget_string, current_user)
осталась одна на все двери и не появилось второго способа пускать в
кабинет.

На что опирается: core.db (те же query/execute), secrets из стандартной
библиотеки. Новых зависимостей не требует.
"""

import secrets
from datetime import datetime, timedelta, timezone

from core.db import execute, query

# Пять минут. Это талон на один вход, а не сессия: человек нажимает
# кнопку на сайте и тут же открывает бота. Час жизни здесь означал бы
# час, в течение которого забытая в чате ссылка ещё работает.
LOGIN_CODE_TTL = timedelta(minutes=5)

# 12 символов из алфавита token_urlsafe. Ровно тот набор, который
# Telegram принимает в параметре start у ссылки t.me/<бот>?start=<...>
# (A-Z a-z 0-9 _ -), поэтому кодировать ничего не нужно.
_CODE_BYTES = 9

# Префикс в ссылке. Нужен, чтобы бот отличил вход от других будущих
# сценариев запуска по ссылке и не пытался разобрать как код приглашения.
DEEP_LINK_PREFIX = "vhod_"


class LoginCodeError(Exception):
    """Код не найден, просрочен или уже использован."""


def _сейчас() -> datetime:
    """UTC, а не Костанай.

    Лимиты в core/limits.py живут по местной дате намеренно: человек
    должен понимать, когда у него сбросится счётчик. Здесь наоборот —
    никто этот момент не видит, а пять минут одинаковы в любом поясе.
    Смешивать пояса в одной таблице дороже, чем выбрать один.
    """
    return datetime.now(timezone.utc)


def построить_ссылку(код: str, имя_бота: str) -> str:
    """Ссылка, по которой человек открывает бота уже с кодом."""
    return f"https://t.me/{имя_бота}?start={DEEP_LINK_PREFIX}{код}"


def контрольные_знаки(код: str) -> str:
    """Последние четыре знака кода — их человек сверяет глазами.

    Зачем: у входа по ссылке есть известная слабость. Злоумышленник может
    создать код у себя, прислать жертве свою ссылку и, когда та
    подтвердит, войти её аккаунтом. Защита здесь не техническая, а
    человеческая: сайт показывает эти четыре знака, бот показывает их же,
    и подтверждение просит их сверить. Совпали — вход начал ты сам.
    """
    return код[-4:]


def выдать_код(db_path=None) -> dict:
    """Заводит новый одноразовый код. Возвращает код и срок его жизни."""
    код = secrets.token_urlsafe(_CODE_BYTES)
    истекает = _сейчас() + LOGIN_CODE_TTL
    execute(
        "INSERT INTO login_codes (code, status, expires_at) VALUES (?, 'pending', ?)",
        (код, истекает.isoformat()),
        db_path=db_path,
    )
    return {
        "код": код,
        "истекает": истекает,
        "живёт_секунд": int(LOGIN_CODE_TTL.total_seconds()),
        "контрольные_знаки": контрольные_знаки(код),
    }


def _взять_живой(код: str, db_path=None) -> dict:
    """Строка кода, если он есть, не просрочен и ещё не использован."""
    строки = query(
        "SELECT code, status, telegram_user_id, first_name, username, expires_at "
        "FROM login_codes WHERE code = ?",
        (код,),
        db_path=db_path,
    )
    if not строки:
        raise LoginCodeError("код не найден")
    строка = dict(строки[0])
    if строка["status"] == "used":
        raise LoginCodeError("код уже использован")
    if datetime.fromisoformat(строка["expires_at"]) <= _сейчас():
        raise LoginCodeError("код просрочен")
    return строка


def код_ждёт_подтверждения(код: str, db_path=None) -> dict:
    """Проверка перед показом подтверждения в боте.

    Отдельно от confirm, потому что бот сначала показывает человеку, что
    именно он подтверждает, и только потом — по нажатию кнопки — вход
    происходит. Подтверждать молча по факту открытия ссылки нельзя: тогда
    достаточно уговорить человека нажать на ссылку.
    """
    строка = _взять_живой(код, db_path=db_path)
    if строка["status"] == "confirmed":
        raise LoginCodeError("код уже подтверждён")
    return строка


def подтвердить(
    код: str,
    telegram_user_id: int,
    first_name: str | None = None,
    username: str | None = None,
    db_path=None,
) -> None:
    """Бот подтверждает: за этим кодом стоит вот этот человек.

    Личность здесь не проверяется и проверять её нечем — она уже
    проверена Telegram: сообщение пришло от конкретного аккаунта, и
    подделать отправителя нельзя.
    """
    _взять_живой(код, db_path=db_path)
    execute(
        "UPDATE login_codes SET status = 'confirmed', telegram_user_id = ?, "
        "first_name = ?, username = ? WHERE code = ?",
        (telegram_user_id, first_name, username, код),
        db_path=db_path,
    )


def забрать_подтверждённый(код: str, db_path=None) -> dict | None:
    """Отдаёт подтверждённый код ОДИН раз и сразу гасит его.

    None означает «ещё ждём», а не ошибку: сайт спрашивает про этот код
    раз в пару секунд, и «пока нет» — обычный ответ. Ошибкой считается
    только просроченный, использованный или несуществующий код — на них
    из _взять_живой прилетает LoginCodeError, и сайту есть что показать.

    Гашение здесь, а не в вызывающем коде: код, отданный дважды, — это
    вход, которым можно воспользоваться дважды.
    """
    строка = _взять_живой(код, db_path=db_path)
    if строка["status"] != "confirmed":
        return None
    execute("UPDATE login_codes SET status = 'used' WHERE code = ?", (код,), db_path=db_path)
    return строка


def убрать_протухшие(db_path=None) -> None:
    """Чистка просроченных и использованных талонов.

    Таблица служебная и растёт от каждой попытки входа. Отдельного
    расписания под неё не заводится: вызывается при выдаче нового кода —
    там же, где строка и появляется.
    """
    execute(
        "DELETE FROM login_codes WHERE expires_at <= ? OR status = 'used'",
        (_сейчас().isoformat(),),
        db_path=db_path,
    )
