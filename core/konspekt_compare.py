"""
core/konspekt_compare.py — сравнивает расшифровку урока с конспектом,
который ученик написал в своей тетради (блок У4, MASTER.md 0.9, п.3).

Зачем модуль: ядро нового продукта — ученик получает не оценку и не
полную расшифровку, а честный список того, чего в его тетради не
хватает по сравнению с уроком. Это разовое LLM-сравнение одного урока с
одной тетрадью по прямому запросу ученика — НЕ аналитика покрытия
программы и не эмбеддинги (это Этап 3, отдельно отложен автором до
сентября 2026, см. CLAUDE.md): там система копит статистику по многим
урокам с порогами косинусной близости, здесь — одноразовое сравнение
двух текстов без накопления и без confidence-скоринга.

Что осознанно не делает: не распознаёт фото — это core/textbook_ocr.py,
тот же LLMClient.complete_json_with_image, что уже работает на
страницах учебника; этот модуль получает уже готовый распознанный текст.
Не ставит оценку и не проверяет подлинность тетради (У4, ловушка). Не
возвращает и не пересказывает расшифровку урока целиком ни при каком
условии — только конкретные пропуски.

На что опирается: core.llm_client.LLMClient.complete_json.
"""

from core.llm_client import LLMClient

SYSTEM_PROMPT = (
    "Ты сравниваешь расшифровку школьного урока с конспектом, который "
    "ученик написал в своей тетради. Найди, чего в конспекте ученика НЕТ "
    "по сравнению с тем, что реально прозвучало на уроке: пропущенные "
    "шаги вывода, недописанные формулы, домашнее задание (если оно "
    "прозвучало на уроке). Формулируй пропуски короткими пунктами, без "
    "оценочных слов ('плохо', 'невнимательно') — только факт, чего не "
    "нашлось. Не пересказывай весь урок и не приводи текст расшифровки "
    "целиком или крупными кусками — только сами пропуски. Если в "
    "конспекте есть всё существенное — прямо скажи, что пропусков не "
    "найдено, не выдумывай их, чтобы список не был пустым."
)
TASK_TEMPLATE = "Расшифровка урока:\n{transcript_text}\n\nКонспект ученика (распознан по фото тетради):\n{notebook_text}"

RESPONSE_SCHEMA = {
    "type": "object",
    "properties": {
        "missing_items": {
            "type": "array",
            "items": {"type": "string"},
            "description": "Конкретные пропуски в конспекте ученика, короткими пунктами. Пустой список, если пропусков нет.",
        },
    },
    "required": ["missing_items"],
}


class KonspektCompareError(Exception):
    """Сравнение не удалось — честная ошибка, не пустой список."""


class NotebookUnreadableError(KonspektCompareError):
    """В тетради нечего сравнивать — распознанного текста почти нет."""


# Находка 6 AUDIT.md: пустой missing_items имеет два прочтения —
# «пропусков нет» и «сравнивать было не с чем», а код знал только
# первое. Ученик с чистым листом получал «в конспекте есть всё
# существенное» — худший из возможных ответов для продукта, который
# весь построен на честности этой сверки.
#
# Порог в символах, а не в словах: распознавание рукописного текста
# возвращает обрывки, и осмысленного деления на слова у них может не
# быть. Число выбрано как заведомо недостижимое для настоящей страницы
# конспекта и заведомо достижимое для мусора вроде «-» или «не видно»;
# при живой эксплуатации его можно двигать, это одна константа.
MIN_NOTEBOOK_TEXT_LENGTH = 30


def notebook_is_unreadable(notebook_text: str) -> bool:
    """Распознанного текста тетради слишком мало, чтобы что-то сверять."""
    return len((notebook_text or "").strip()) < MIN_NOTEBOOK_TEXT_LENGTH


async def compare_notebook_to_transcript(
    transcript_text: str,
    notebook_text: str,
    llm_client: LLMClient | None = None,
) -> list[str]:
    """Возвращает список пропусков (может быть пустым — это не ошибка,
    значит конспект полный). Пустой ОТВЕТ модели (не найдено поле
    missing_items вовсе) — честная ошибка (2.7: не подставлять
    правдоподобное вместо известного), а не молчаливый пустой список.

    Пустая или почти пустая тетрадь — NotebookUnreadableError, а НЕ
    пустой список пропусков: у пустого списка два прочтения, и путать их
    здесь нельзя (Находка 6 AUDIT.md)."""
    # Проверка до вызова модели: сравнивать нечего — значит и спрашивать
    # не о чем, и деньги за вызов тратить не за что (грабля 2.7 — не
    # подставлять правдоподобное вместо известного).
    if notebook_is_unreadable(notebook_text):
        raise NotebookUnreadableError(
            "распознанного текста тетради слишком мало для сравнения"
        )

    client = llm_client or LLMClient()
    owns_client = llm_client is None
    try:
        result = await client.complete_json(
            system=SYSTEM_PROMPT,
            user=TASK_TEMPLATE.format(transcript_text=transcript_text, notebook_text=notebook_text),
            schema=RESPONSE_SCHEMA,
        )
    finally:
        if owns_client:
            await client.aclose()

    if "missing_items" not in result:
        raise KonspektCompareError("модель не вернула обязательное поле missing_items")
    missing_items = result["missing_items"]
    if not isinstance(missing_items, list):
        raise KonspektCompareError("модель вернула missing_items не списком")
    return [str(item) for item in missing_items]
