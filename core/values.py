def list_values() -> list[dict]:
    return [{"key": k, **v} for k, v in VALUES.items()]


def find_value_key_by_name(name: str) -> str | None:
    """Ключ ценности по её отображаемому имени (без учёта регистра и
    лишних пробелов) — учитель вводит название текстом в боте, а не
    внутренний ключ справочника."""
    normalized = " ".join(name.strip().lower().split())
    for key, value in VALUES.items():
        if value["name"].lower() == normalized:
            return key
    return None
