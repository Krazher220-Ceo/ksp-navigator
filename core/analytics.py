"""
core/analytics.py — аналитика продукта по обезличенным событиям (блок Ф14).

Зачем модуль: понять, пользуются ли продуктом на самом деле и где люди
останавливаются. Считается по событиям приложения — какое действие,
когда, чем закончилось, — и ни по чему больше.

Что осознанно НЕ делает и делать не будет:
  — не считает рейтинг педагогов. Как только аналитика учебного процесса
    превращается в оценку человека, доступ в школы закрывается — и
    правильно делает;
  — не читает содержимое документов: ни тем уроков, ни текстов
    конспектов, ни расшифровок. Отсюда возвращаются только числа;
  — не возвращает имён, идентификаторов и вообще ничего, по чему можно
    узнать конкретного человека. Педагоги считаются, но не перечисляются.

Откуда числа: таблицы tasks (что делали и чем кончилось) и usage_daily
(сколько операций в день). Отдельной таблицы событий в проекте нет —
завести её значит менять схему, а это решение автора. Тех событий, что
уже пишутся, для шести показателей из документации достаточно.

На что опирается: core.db. Ни одной новой зависимости.
"""

from datetime import datetime, timedelta

from core.db import query

# Педагог считается работающим, если за это число дней он собрал хотя бы
# один документ. Просто зайти и посмотреть — недостаточно: регистрации
# мы не считаем принципиально, зарегистрироваться легко, вернуться трудно.
ОКНО_АКТИВНОСТИ_ДНЕЙ = 30

# Виды задач, каждая из которых заканчивается готовым документом.
ДОКУМЕНТНЫЕ_ЗАДАЧИ = ("generate_ksp", "generate_ktp", "generate_konspekt")


def _граница(дней: int) -> str:
    return (datetime.now() - timedelta(days=дней)).isoformat(sep=" ")


def collect(db_path=None) -> dict:
    """
    Шесть показателей из документации, все — числа.

    Ни одного имени, ни одной темы урока, ни одного идентификатора
    человека в ответе нет и появиться не может: запросы ниже возвращают
    только COUNT и группировки по типу действия.
    """
    за_30 = _граница(ОКНО_АКТИВНОСТИ_ДНЕЙ)
    за_7 = _граница(7)

    # 1. Сколько педагогов пользуются: собрали хотя бы один документ за
    # 30 дней. Считаем ИМЕННО документы, а не входы.
    активные = query(
        "SELECT COUNT(DISTINCT teacher_id) AS n FROM ("
        "  SELECT teacher_id FROM generated_ksp WHERE created_at >= ?"
        "  UNION ALL"
        "  SELECT teacher_id FROM konspekty WHERE created_at >= ?"
        ")",
        (за_30, за_30),
        db_path=db_path,
    )[0]["n"]

    # 2. Сколько документов собрано, по видам.
    документы = {
        "konspekt": query("SELECT COUNT(*) AS n FROM konspekty", db_path=db_path)[0]["n"],
        "ksp": query("SELECT COUNT(*) AS n FROM generated_ksp", db_path=db_path)[0]["n"],
    }

    # 3. Чем пользуются чаще: доля каждого действия среди завершённых.
    по_типам = query(
        "SELECT type, status, COUNT(*) AS n FROM tasks GROUP BY type, status",
        db_path=db_path,
    )
    действия: dict[str, dict[str, int]] = {}
    for строка in по_типам:
        запись = действия.setdefault(строка["type"], {"done": 0, "failed": 0, "всего": 0})
        if строка["status"] in ("done", "failed"):
            запись[строка["status"]] += строка["n"]
        запись["всего"] += строка["n"]

    # 4. Когда работают: распределение по дням недели. Только счётчики,
    # без привязки к человеку.
    по_дням = {номер: 0 for номер in range(7)}
    for строка in query("SELECT created_at FROM tasks WHERE created_at >= ?", (за_30,), db_path=db_path):
        try:
            дата = datetime.fromisoformat(str(строка["created_at"]).replace(" ", "T"))
        except (ValueError, TypeError):
            continue
        по_дням[дата.weekday()] += 1

    # 5. Где останавливаются: сколько задач каждого вида не дошло до
    # результата. Это и есть «воронка» в том виде, в каком её можно
    # честно посчитать по имеющимся событиям.
    провалы = {тип: значения.get("failed", 0) for тип, значения in действия.items()}

    # 6. Возвращаются ли: сколько педагогов собрали документ и за
    # последние 7 дней, и в предыдущие 30. Полноценные когорты требуют
    # таблицы событий, которой нет; это её честное приближение, и
    # называется оно так же честно.
    вернувшиеся = query(
        "SELECT COUNT(DISTINCT a.teacher_id) AS n FROM ("
        "  SELECT teacher_id FROM generated_ksp WHERE created_at >= ?"
        "  UNION SELECT teacher_id FROM konspekty WHERE created_at >= ?"
        ") a JOIN ("
        "  SELECT teacher_id FROM generated_ksp WHERE created_at < ? AND created_at >= ?"
        "  UNION SELECT teacher_id FROM konspekty WHERE created_at < ? AND created_at >= ?"
        ") b ON a.teacher_id = b.teacher_id",
        (за_7, за_7, за_7, за_30, за_7, за_30),
        db_path=db_path,
    )[0]["n"]

    return {
        "window_days": ОКНО_АКТИВНОСТИ_ДНЕЙ,
        "active_teachers": активные,
        "documents": документы,
        "actions": действия,
        "by_weekday": [по_дням[номер] for номер in range(7)],
        "failures": провалы,
        "returned_teachers": вернувшиеся,
    }
