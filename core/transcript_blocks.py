"""
core/transcript_blocks.py — расшифровка, разложенная на реплики по времени.

Зачем модуль: xAI отдаёт время начала и конца каждого слова, и из этого
без единого обращения к нейросети получается то, что нарисовано в
макетах: «08:14 — …», «08:41 — …». Сплошное полотно текста на 45 минут
урока читать невозможно, а разбить его по паузам — обычная арифметика.

Что осознанно не делает: не пересказывает, не сокращает и не решает, что
в уроке главное. Здесь нет ни одного вызова LLM и не будет: решение
автора от 02.09.2026 — после расшифровки искусственный интеллект не
используется, транскрипт показывается как есть. Обобщает его позже
сборка КСП, отдельным промптом.

Не выдумывает время. Нет слова с отметкой — блок остаётся без времени, а
не получает придуманное «примерно тут». Это то же правило, по которому
живёт вся аналитика проекта: система говорит только то, что видела.
"""

# Пауза, после которой начинается новая реплика. Полторы секунды — это
# ощутимая остановка в речи учителя (смена мысли, вопрос классу), а не
# вдох между словами.
ПАУЗА_СЕКУНД = 1.5

# Верхние границы блока: чтобы монолог без пауз не превратился в
# единственный абзац на весь урок.
МАКС_ЗНАКОВ = 260
МАКС_СЕКУНД = 40.0


def собрать_блоки(слова: list[dict]) -> list[dict]:
    """Группирует слова в реплики: [{"start", "end", "text"}, ...].

    Границей служит пауза между словами либо накопленный размер блока.
    Слова без отметок времени пропускаются молча — их место в тексте
    сохраняется, а придуманного времени у них не появляется.
    """
    блоки: list[dict] = []
    текущие: list[str] = []
    начало = конец = None

    for слово in слова:
        if not isinstance(слово, dict):
            continue
        текст = str(слово.get("text") or "").strip()
        if not текст:
            continue
        s, e = слово.get("start"), слово.get("end")
        if not isinstance(s, (int, float)) or not isinstance(e, (int, float)):
            continue

        пауза = начало is not None and (s - конец) >= ПАУЗА_СЕКУНД
        длинно = начало is not None and (
            len(" ".join(текущие)) >= МАКС_ЗНАКОВ or (e - начало) >= МАКС_СЕКУНД
        )
        if текущие and (пауза or длинно):
            блоки.append({"start": round(начало, 2), "end": round(конец, 2), "text": " ".join(текущие)})
            текущие, начало = [], None

        if начало is None:
            начало = float(s)
        конец = float(e)
        текущие.append(текст)

    if текущие and начало is not None:
        блоки.append({"start": round(начало, 2), "end": round(конец, 2), "text": " ".join(текущие)})
    return блоки


def как_время(секунды: float) -> str:
    """Секунды от начала записи в «MM:SS» или «H:MM:SS» для длинного урока."""
    всего = int(секунды)
    часы, остаток = divmod(всего, 3600)
    минуты, сек = divmod(остаток, 60)
    return f"{часы}:{минуты:02d}:{сек:02d}" if часы else f"{минуты:02d}:{сек:02d}"
